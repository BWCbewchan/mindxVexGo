 assert.match(await button.innerText(),/Còn 3 \/ 3/);
 await button.click();await page.waitForFunction(sku=>JSON.parse(localStorage.getItem('mindx-assembly-project-v1:vexiq:wheel-kit-ui')).parts.some(p=>p.sku===sku),sku);
 await page.waitForFunction(()=>!document.querySelector('#title').disabled);assert.match(await button.innerText(),/Còn 2 \/ 3/);
 const saved=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),key);
 assert.equal(saved.kit.items['228-2500-209'],3);assert.equal(saved.kit.items['228-2500-1208'],3);
