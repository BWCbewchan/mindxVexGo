 assert.equal(await button.isEnabled(),true,'Travel Wheel must be enabled when its hub and tire are in stock');
 assert.match(await button.innerText(),/Còn 2 \/ 2/);
 await page.locator('#kit-status').click();
 const settings=page.frameLocator('iframe[title="Cài đặt số lượng bộ kit"]');
 await settings.getByRole('searchbox',{name:'Tìm linh kiện bộ kit'}).fill('Travel Wheel');
 const row=settings.getByRole('row').filter({hasText:name});
 await row.waitFor();assert.match(await row.innerText(),/1.*Small Wheel Hub.*1.*Tire/s);
 await row.getByText('Chỉnh lốp và vành',{exact:true}).click();
 const tires=row.getByLabel('Số lượng Tire (200 mm Travel) cho Travel Wheel trong 1 bộ',{exact:true});
 await tires.fill('3');
 const hubs=row.getByLabel('Số lượng Small Wheel Hub (44 mm) cho Travel Wheel trong 1 bộ',{exact:true});
 await hubs.fill('3');
 await page.screenshot({path:'artifacts/vexiq-wheels/travel-wheel-kit-settings.png'});
