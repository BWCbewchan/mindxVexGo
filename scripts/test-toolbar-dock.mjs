import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:960}});
 await page.goto((process.env.TEST_BASE_URL||'http://localhost:3102')+'/studio',{waitUntil:'domcontentloaded'});
 await page.getByRole('button',{name:'Continue to editor'}).click();
 await page.locator('iframe[title="VEXcode GO editor"]').waitFor();
 const frame=await page.locator('iframe[title="VEXcode GO editor"]').elementHandle().then(e=>e.contentFrame());
 await frame.locator('.studio-toolbar-actions').waitFor({timeout:60000});
 assert.equal(await page.locator('.studio-bar').count(),0);
 assert.equal(await frame.locator('.topmenu').count(),1);
 await frame.getByRole('button',{name:'File',exact:true}).click();
 const chooser=page.waitForEvent('filechooser');
 await frame.getByText('Load From Your Device',{exact:true}).click();
 await (await chooser).setFiles('scripts/fixtures/controls.goblocks');
 await frame.getByRole('button',{name:'⌨ Controls',exact:true}).click();
 await page.getByRole('button',{name:'+ Add control',exact:true}).click();
 await page.getByRole('combobox',{name:'Function 1',exact:true}).selectOption('drive forward');
 const dock=page.getByRole('navigation',{name:'Assigned control keys'});
 await dock.waitFor();
 await page.getByRole('button',{name:'Close controller',exact:true}).click();
 await page.getByRole('button',{name:'Hide dock',exact:true}).click();
 assert.equal(await dock.count(),0);
 await frame.getByRole('button',{name:'▤ Dock',exact:true}).click();
 await dock.waitFor();
 assert.equal(await dock.locator('.dock-key').count(),1);
 await frame.getByRole('button',{name:'▤ Dock',exact:true}).click();
 await dock.waitFor({state:'detached'});
 await frame.getByRole('button',{name:'▤ Dock',exact:true}).click();
 await dock.waitFor();
 await page.keyboard.down('w');
 await dock.locator('.is-pressed').waitFor();
 await page.keyboard.up('w');
 await dock.locator('.is-pressed').waitFor({state:'detached'});
 await page.screenshot({path:'artifacts/unified-toolbar-dock.png'});
 await page.setViewportSize({width:390,height:844});
 await frame.getByRole('button',{name:'▤ Dock',exact:true}).click();
 await dock.waitFor({state:'detached'});
 await frame.getByRole('button',{name:'▤ Dock',exact:true}).click();
 await dock.waitFor();
 await page.screenshot({path:'artifacts/unified-toolbar-mobile.png'});
 console.log('PASS: single toolbar; Controls opens; dock hides and reopens from both controls; mappings retained; key highlight; mobile toggle.');
} finally {await browser.close();}
