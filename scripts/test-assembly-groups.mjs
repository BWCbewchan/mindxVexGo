import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {chromium} from '@playwright/test';

const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1500,height:1000},acceptDownloads:true});
 await page.addInitScript(()=>{if(location.pathname==='/assembly/editor.html'&&!sessionStorage.getItem('assembly-group-ui-seeded')){localStorage.setItem('mindx-vexgo-assembly-v1',JSON.stringify({version:1,title:'Group UI test',parts:[{id:'beam-a',sku:'228-2500-003',label:'Beam A',position:[-45,0,0],rotation:[0,0,0]},{id:'beam-b',sku:'228-2500-004',label:'Beam B',position:[45,0,0],rotation:[0,0,0]}],groups:[],steps:[]}));sessionStorage.setItem('assembly-group-ui-seeded','1');}});
 await page.goto('http://localhost:3120/assembly');
 const frame=page.frameLocator('iframe');
 await frame.locator('#status').filter({hasText:'Draft saved locally'}).waitFor({timeout:60000});
 await frame.locator('#objects button').nth(1).waitFor();
 await frame.locator('#fit').click();
 const canvas=await frame.locator('canvas').boundingBox();
 assert.ok(canvas&&canvas.width>100&&canvas.height>100,'3D canvas is ready');
 await page.mouse.move(canvas.x+4,canvas.y+4);
 await page.keyboard.down('Control');
 await page.mouse.down({button:'left'});
 await page.mouse.move(canvas.x+canvas.width-4,canvas.y+canvas.height-4,{steps:8});
 await page.mouse.up({button:'left'});
 await page.keyboard.up('Control');
 await frame.locator('#objects button[aria-pressed="true"]').nth(1).waitFor();
 assert.equal(await frame.locator('#objects button[aria-pressed="true"]').count(),2,'Ctrl-drag selects both visible parts');
 await frame.locator('#viewport').press('Control+g');
 await frame.locator('#groups .layer-row').waitFor();
 assert.equal(await frame.locator('#groups .layer-row').count(),1,'Ctrl+G creates a layer group');
 let project=await page.frames().find(item=>item.url().includes('editor.html')).evaluate(()=>JSON.parse(localStorage.getItem('mindx-vexgo-assembly-v1')));
 assert.ok(project.parts.every(part=>part.groupId===project.groups[0].id),'group membership is autosaved');
 const row=frame.locator('#groups .layer-row');
 await row.getByRole('button',{name:'Select group Group 1'}).click();
 await row.getByRole('button',{name:'Hide group Group 1'}).click();
 assert.equal(await row.getByRole('button',{name:'Show group Group 1'}).count(),1,'layer visibility toggles');
 await row.getByRole('button',{name:'Lock group Group 1'}).click();
 assert.equal(await frame.locator('#transforms label').count(),0,'locked group cannot be precision-transformed');
 const rename=row.getByRole('textbox',{name:'Rename group Group 1'});
 await rename.fill('Drive base');
 await rename.press('Tab');
 const downloadPromise=page.waitForEvent('download');
 await frame.locator('#save').click();
 const download=await downloadPromise;
 const file=await download.path();
 const exported=await readFile(file);
 await frame.locator('#open').setInputFiles({name:'grouped.json',mimeType:'application/json',buffer:exported});
 await frame.locator('#groups .layer-row input').waitFor();
 assert.equal(await frame.locator('#groups .layer-row input').inputValue(),'Drive base','exported project reopens with layer name');
 project=await page.frames().find(item=>item.url().includes('editor.html')).evaluate(()=>JSON.parse(localStorage.getItem('mindx-vexgo-assembly-v1')));
 assert.ok(project.groups[0].locked&&!project.groups[0].visible,'visibility and lock survive save/open');
 await frame.locator('#groups .layer-row button[aria-label="Show group Drive base"]').click();
 await frame.locator('#groups .layer-row button[aria-label="Unlock group Drive base"]').click();
 await frame.locator('#groups .layer-row').getByRole('button',{name:'Ungroup'}).click();
 project=await page.frames().find(item=>item.url().includes('editor.html')).evaluate(()=>JSON.parse(localStorage.getItem('mindx-vexgo-assembly-v1')));
 assert.equal(project.groups.length,0,'ungroup removes layer metadata');
 assert.ok(project.parts.every(part=>!part.groupId),'ungroup preserves parts as independent objects');
 await frame.locator('#objects button').nth(0).click();await frame.locator('#objects button').nth(1).click({modifiers:['Control']});await frame.locator('#viewport').press('Control+g');
 await frame.locator('#groups .layer-row').waitFor();await frame.locator('#viewport').press('Control+Shift+g');
 await frame.locator('#groups .layer-row').waitFor({state:'detached'});
 console.log('PASS: Ctrl-drag selection, Ctrl+G grouping, layer controls, exported project persistence and Ctrl+Shift+G ungrouping.');
}finally{await browser.close();}
