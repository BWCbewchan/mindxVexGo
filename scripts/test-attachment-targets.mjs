import assert from 'node:assert/strict';
import {attachmentTargets,focusedAttachmentTargets} from '../public/assembly/attachment-targets.js';

const pins=Array.from({length:4},(_,i)=>({id:'pin'+i,kind:'pin',point:[i*12,0,0],normal:[0,1,0],radius:2.2,depth:4}));
const refs={connector:pins,beam:[{id:'hole',kind:'hole',point:[0,0,0],normal:[0,-1,0],radius:2.2,depth:4}]};
const fixed={id:'fixed',sku:'connector',position:[0,0,0],rotation:[0,0,0]},moving={id:'moving',sku:'beam',position:[0,0,0],rotation:[0,0,0]};
const candidate={target:fixed,targetRef:pins[0],depth:2,parts:[fixed,moving]};
const available=attachmentTargets(candidate,[moving],refs);
assert.equal(available.length,4,'All four compatible connector ends appear');
assert.equal(available.filter(point=>point.primary).length,1);
assert.equal(available.filter(point=>point.matched).length,1,'Alternatives do not claim to be already aligned');
assert.equal(attachmentTargets(candidate,[moving],refs,new Set(['fixed|pin2'])).length,3);
candidate.matches=pins.map(pin=>({target:fixed.id,sourceRef:'hole',targetRef:pin.id,depth:2}));
const matched=attachmentTargets(candidate,[moving],refs);
assert.equal(matched.filter(point=>point.matched).length,4,'Every simultaneous pin contact is highlighted');
assert.equal(new Set(matched.map(point=>point.partId+'|'+point.refId)).size,4);
candidate.matches=null;
candidate.contacts=pins.map(pin=>({part:moving.id,target:fixed.id,sourceRef:'hole',targetRef:pin.id,depth:2}));
assert.equal(attachmentTargets(candidate,[moving],refs).filter(point=>point.matched).length,4,'Group contacts use the stationary receiving side');
candidate.sourceRef=refs.beam[0];
const withSource=attachmentTargets(candidate,[moving],refs,new Set(),{includeSource:true});
assert.equal(withSource.filter(point=>point.partId===moving.id).length,1,'Moving component sockets are displayed alongside receiving connector ends');
assert.equal(withSource.filter(point=>point.partId===fixed.id).length,4);
const other={...moving,id:'other',position:[100,0,0]};
const groupCandidate={...candidate,source:moving,contacts:[],parts:[fixed,moving,other]};
const groupTargets=attachmentTargets(groupCandidate,[moving,other],refs,new Set(),{includeSource:true});
assert.equal(groupTargets.find(point=>point.partId===other.id).matched,false,'A shared reference ID on another group member is not a matched contact');
const crowded=Array.from({length:150},(_,i)=>({partId:'fan',refId:String(i),point:available[0].point.clone().addScalar(i*.008),matched:i<4,primary:i===0}));
const focused=focusedAttachmentTargets(crowded);
assert.ok(focused.length<=8);
assert.equal(focused.filter(point=>point.matched).length,4,'Keep the four simultaneous connections before alternatives');
assert.ok(focused.every(point=>point.matched||point.point.distanceTo(crowded[0].point)<=.03));
assert.equal(focusedAttachmentTargets([crowded[0],{...crowded[0],refId:'same-location',primary:false}]).length,1,'A seated pin and its hole share one marker');
assert.equal(focusedAttachmentTargets(crowded,{project:()=>({x:100,y:100})}).length,1,'Overlapping screen markers collapse');
assert.deepEqual(focusedAttachmentTargets(crowded,{project:()=>null}),[],'Off-screen markers are hidden');
assert.equal(focusedAttachmentTargets([]).length,0);
console.log('PASS: every compatible connector end, occupied-port filtering, simultaneous contacts, group contacts, and primary/alternative distinction.');
