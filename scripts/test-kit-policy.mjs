import assert from 'node:assert/strict';
import fs from 'node:fs';
import {defaultKitProfile,validateKitProfile,parseKitFile,kitReport,assertKitChange} from '../public/assembly/kit-policy.js';
import {withElectronics} from '../public/assembly/electronics.js';
import {validateProjectFile} from '../public/assembly/project-store.js';
const catalog=JSON.parse(fs.readFileSync('public/assembly/parts.json','utf8'));
const profile=defaultKitProfile(catalog,'vexgo');
const brain=catalog.find(p=>p.name==='Brain').id,motor=catalog.find(p=>p.name==='Motor').id;
assert.equal(kitReport([],catalog,profile).find(row=>row.name==='Red Square Beam').available,6);
assert.equal(kitReport([],catalog,profile).find(row=>row.name==='Motor').available,3);
const parts=sku=>[{sku}];
assert.equal(kitReport(parts(brain),catalog,profile).find(r=>r.skus.includes(brain)).remaining,0);
assert.throws(()=>assertKitChange(parts(brain),[{sku:brain},{sku:brain}],catalog,profile),/Brain/);
assert.doesNotThrow(()=>assertKitChange([{sku:brain},{sku:brain}],[{sku:brain},{sku:brain},{sku:motor}],catalog,profile));
assert.doesNotThrow(()=>assertKitChange(parts(brain),[{sku:brain},{sku:brain}],catalog,{...profile,count:2}));
assert.doesNotThrow(()=>assertKitChange(parts(brain),[{sku:brain},{sku:brain}],catalog,{...profile,enforce:false}));
assert.deepEqual(parseKitFile(JSON.stringify(profile),'kit.json',catalog,'vexgo'),profile);
const csv=parseKitFile(`sku,quantity\n${brain},1\n${motor},2`,'kit.csv',catalog,'vexgo');
assert.equal(kitReport([{sku:motor},{sku:motor}],catalog,csv).find(r=>r.skus.includes(motor)).remaining,0);
assert.throws(()=>parseKitFile(`sku,quantity\n${brain},1.5`,'kit.csv',catalog,'vexgo'),/số nguyên/);
assert.throws(()=>parseKitFile('sku,quantity\nmissing,2','kit.csv',catalog,'vexgo'),/không thuộc/);
assert.throws(()=>validateKitProfile({...profile,count:0},catalog,'vexgo'),/1.*100/);
assert.throws(()=>validateKitProfile({...profile,platform:'vexiq'},catalog,'vexgo'),/VEX/);
assert.throws(()=>validateKitProfile({...profile,items:{...profile.items,[brain]:-1}},catalog,'vexgo'),/số nguyên/);
const wheel=[{sku:'228-2500-1383'},{sku:'228-2500-1383'}];
assert.equal(kitReport(wheel,catalog,profile).find(r=>r.skus.includes('228-2500-207')).used,2);
assert.throws(()=>assertKitChange(wheel,[...wheel,{sku:'228-2500-207'}],catalog,profile),/Tire/);
const iq=JSON.parse(fs.readFileSync('public/assembly/iq/parts.json','utf8'));
assert.equal(kitReport([{sku:'228-2560'}],iq,defaultKitProfile(iq,'vexiq')).find(r=>r.skus.includes('228-2560')).available,4);
assert.equal(kitReport([{sku:'228-2540'}],iq,defaultKitProfile(iq,'vexiq')).find(r=>r.skus.includes('228-2540')).available,0,'Gen 1 Brain must not consume a Gen 2 Brain quota');
const iqPins=kitReport([{sku:'228-2500-060'},{sku:'228-2500-2260'}],iq,defaultKitProfile(iq,'vexiq')).find(r=>r.skus.includes('228-2500-060'));assert.equal(iqPins.used,2);assert.equal(iqPins.available,221);
assert.throws(()=>assertKitChange([],parts(iq[0].id),iq,defaultKitProfile(iq,'vexiq')),/bộ kit/);
assert.doesNotThrow(()=>assertKitChange([],parts(brain),catalog,null));
const project={version:1,platform:'vexgo',title:'Kit backup',parts:[],groups:[],steps:[],kit:profile};
assert.deepEqual(validateProjectFile(JSON.parse(JSON.stringify(project)),'vexgo',catalog).kit,profile,'Project import must retain validated stock');
assert.throws(()=>validateProjectFile({...project,kit:{...profile,count:-1}},'vexgo',catalog));
assert.equal(withElectronics(Array.from({length:249},()=>({sku:'228-2500-001'})),{sku:motor,position:[0,0,0]},catalog,undefined,()=>false).length,1,'Excluded companion devices must not consume the CAD part limit');
console.log('PASS: limits, kit count, imported quantities, invalid files, existing overages, integrated tires and IQ custom stock.');
