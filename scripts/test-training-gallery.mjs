import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const catalog=JSON.parse(await fs.readFile('app/training/missions.json','utf8'));
const browser=await chromium.launch({channel:'chrome'});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('dialog',d=>d.accept());
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto((process.env.TEST_BASE_URL||'http://localhost:3113')+'/training');
 await page.getByRole('heading',{name:/A new field/}).waitFor();
 assert.equal(await page.locator('.lesson-card').count(),catalog.length+1);
 await page.getByRole('searchbox',{name:'Find a mission'}).fill('labyrinth');
 assert.ok(await page.locator('.lesson-card').count()>=2);
 await page.getByRole('searchbox',{name:'Find a mission'}).fill('');
 await page.getByRole('group',{name:'Difficulty'}).getByRole('button',{name:/^Beginner/}).click();
 assert.equal(await page.locator('.lesson-card').count(),catalog.filter(l=>l.level.includes('BEGINNER')).length);
 await page.getByRole('group',{name:'Difficulty'}).getByRole('button',{name:/^All levels/}).click();
 assert.equal(await page.locator('iframe').count(),0,'gallery should not load the editor');
 await page.screenshot({path:'artifacts/training-gallery.png'});
 await page.getByRole('button',{name:'Practice First journey',exact:true}).click();
 let editor=await page.locator('iframe').elementHandle().then(e=>e.contentFrame());
 await editor.waitForFunction(()=>!!window.VexStudio);
 await editor.evaluate(()=>window.__galleryTest=123);
 await page.getByRole('button',{name:'Load demo code'}).click();
 await page.getByRole('button',{name:'Hide map',exact:true}).click();
 assert.equal(await page.locator('#training-map-panel').isVisible(),false);
 assert.equal(await page.getByRole('button',{name:'Stop',exact:false}).isVisible(),true);
 const width=await page.locator('.training-code').boundingBox();assert.ok(width.width>1400);
 await page.getByRole('button',{name:'Run code',exact:false}).click();
 await page.waitForFunction(()=>document.querySelector('.training-status')?.textContent==='Program finished',{},{timeout:20000}).catch(async error=>{console.log('Hidden-map run:',await page.locator('.training-status').textContent(),await page.locator('.training-telemetry').textContent(),await editor.evaluate(()=>({hidden:document.hidden,running:window.VexTraining.running})));throw error;});
 await page.getByRole('button',{name:'Show map',exact:true}).click();
 assert.equal(await editor.evaluate(()=>window.__galleryTest),123,'toggle must keep the iframe alive');
 assert.match(await page.locator('.training-telemetry').innerText(),/700/);
 await page.getByRole('button',{name:'All missions',exact:false}).click();
 await page.getByRole('button',{name:'Practice Around the corner',exact:true}).click();
 await page.getByRole('heading',{name:'Around the corner',exact:true}).waitFor();
 editor=await page.locator('iframe').elementHandle().then(e=>e.contentFrame());
 await editor.waitForFunction(()=>!!window.VexStudio);
 assert.equal((await editor.locator('.blocklyBlockCanvas').first().textContent()).includes('700'),false,'each mission starts with its own code');
 assert.equal(await page.locator('#training-map-panel').isVisible(),true);
 await page.getByRole('button',{name:'All missions',exact:false}).click();
 await page.getByRole('button',{name:'Practice First journey',exact:true}).click();
 editor=await page.locator('iframe').elementHandle().then(e=>e.contentFrame());
 await editor.waitForFunction(()=>document.querySelector('.blocklyBlockCanvas')?.textContent.includes('700'));
 await page.getByRole('button',{name:'All missions',exact:false}).click();
 const field={name:'Imported maze',width:1200,height:1200,start:{x:200,y:600,heading:90},goal:{x:900,y:600,radius:70},walls:[]};
 await page.locator('.library-tools input').setInputFiles({name:'field.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({version:1,field}))});
 await page.getByRole('heading',{name:'Imported maze'}).waitFor();
 await page.getByRole('button',{name:'All missions',exact:false}).click();
 assert.equal(await page.locator('.lesson-card').count(),catalog.length+2);
 await page.reload();
 await page.getByRole('button',{name:'Practice Imported maze',exact:true}).waitFor();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'artifacts/training-gallery-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Practice Imported maze',exact:true}).click();
 await page.getByRole('button',{name:'Hide map',exact:true}).click();
 await page.getByRole('button',{name:'Show map',exact:true}).click();
 assert.equal(await page.locator('#training-map-panel').isVisible(),true);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: 72 missions plus custom field, search/filter, lazy editor, map toggle preserves running robot/code, Stop remains available, per-mission code isolation and restore, imported library persistence, mobile layout.');
}finally{await browser.close();}
