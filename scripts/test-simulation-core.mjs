import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {robotDevices,defaultDrive,validateDrive,playground} from '../public/simulation/config.js';
const project={platform:'vexgo',parts:[{id:'l',sku:'269-6690-000'},{id:'r',sku:'269-6690-000'},{id:'b',sku:'269-6685-000'},{id:'p',sku:'269-6686-000'},{id:'w1',sku:'228-2500-1383'},{id:'w2',sku:'228-2500-1383'}]},before=JSON.stringify(project);
const devices=robotDevices(project,[]),drive=defaultDrive(devices);
assert.equal(devices.motors.length,2);assert.equal(devices.wheels.length,2);assert.equal(devices.eye,false);
assert.equal(validateDrive(drive,devices).leftMotor,'l');
assert.throws(()=>validateDrive({...drive,rightMotor:'l'},devices),/khác nhau/);
assert.throws(()=>validateDrive({...drive,wheelDiameter:0},devices),/bánh/);
assert.throws(()=>validateDrive({...drive,maxRpm:NaN},devices),/RPM/);
assert.equal(JSON.stringify(project),before);
assert.throws(()=>validateDrive(drive,{...devices,brain:false}),/Brain/);
const iqColor=robotDevices({platform:'vexiq',parts:[{id:'color',sku:'228-3012'}]});assert.equal(iqColor.colorEye,true);assert.equal(iqColor.distanceEye,false);
const iqDistance=robotDevices({platform:'vexiq',parts:[{id:'distance',sku:'228-3011'}]});assert.equal(iqDistance.colorEye,false);assert.equal(iqDistance.distanceEye,true);
const field=playground('grid',drive,devices,180);assert.equal(field.robot.radius,180);
const context={};vm.runInNewContext(fs.readFileSync('public/training-engine.js','utf8'),context);
const engine=context.createTrainingEngine({...field,start:{x:300,y:700,heading:90},walls:[{x:1000,y:0,width:2,height:2400}]});
engine.command('drive',1500,9000);for(let i=0;i<10&&engine.moving;i++)engine.tick(.05);
assert.ok(engine.state.x<=820,'Large/high-speed robots must stop before their CAD footprint crosses a thin wall');assert.equal(engine.state.collision,true);
engine.reset({...field,start:{x:300,y:700,heading:90},walls:[]});engine.command('drive',700,250);for(let i=0;i<300;i++)engine.tick(.01);assert.ok(Math.abs(engine.state.x-1000)<.001);
console.log('PASS: custom robot devices, drivetrain validation, unchanged CAD, CAD footprint collision and swept high-speed motion.');
